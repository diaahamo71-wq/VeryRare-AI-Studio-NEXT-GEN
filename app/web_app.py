"""Local-only HTTP API for the VeryRare Studio UI.

Run with: python -m uvicorn app.web_app:app --host 127.0.0.1 --port 8765
The server intentionally binds to loopback in the documented command. It does not
provide cloud APIs, shell execution, arbitrary paths, or silent output overwrites.
"""
from __future__ import annotations

import os
import re
import uuid
from pathlib import Path
from typing import Annotated

from fastapi import FastAPI, File, Form, HTTPException, UploadFile
from fastapi.responses import FileResponse
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel, Field

from app.audio_engine import MixSettings, analyze_file, mix_tracks

ROOT = Path(__file__).resolve().parents[1]
UI_DIR = ROOT / "frontend"
WORKSPACE = Path(os.environ.get("VERYRARE_AUDIO_ROOT", str(ROOT / "workspace"))).expanduser().resolve()
WORKSPACE.mkdir(parents=True, exist_ok=True)
MAX_UPLOAD_BYTES = 500 * 1024 * 1024
CHUNK_SIZE = 1024 * 1024

app = FastAPI(
    title="VeryRare AI Studio",
    version="0.1.0",
    description="Loopback-only local audio studio API. Audio is not uploaded to cloud services.",
)
app.mount("/assets", StaticFiles(directory=str(UI_DIR / "assets"), check_dir=False), name="assets")


class MixRequest(BaseModel):
    vocal_file: str = Field(min_length=1, max_length=200)
    beat_file: str = Field(min_length=1, max_length=200)
    vocal_gain_db: float = Field(default=0.0, ge=-18, le=12)
    beat_gain_db: float = Field(default=-3.0, ge=-18, le=12)
    highpass_hz: float = Field(default=80.0, ge=20, le=500)
    presence_db: float = Field(default=1.5, ge=-6, le=6)
    compression_ratio: float = Field(default=2.0, ge=1, le=6)
    compression_threshold_db: float = Field(default=-18.0, ge=-36, le=-6)
    reverb_mix: float = Field(default=0.08, ge=0, le=0.35)
    delay_mix: float = Field(default=0.0, ge=0, le=0.30)
    delay_ms: float = Field(default=260.0, ge=60, le=700)
    master_peak_dbfs: float = Field(default=-1.0, ge=-3, le=-0.1)


def _safe_workspace_file(name: str, *, must_exist: bool = True) -> Path:
    # Only accept a basename generated by this service, never a user-supplied path.
    if not name or Path(name).name != name or name in {".", ".."} or "/" in name or "\\" in name:
        raise HTTPException(status_code=400, detail="Invalid workspace file name.")
    path = (WORKSPACE / name).resolve()
    if path.parent != WORKSPACE:
        raise HTTPException(status_code=400, detail="File must remain inside the local workspace.")
    if must_exist and not path.is_file():
        raise HTTPException(status_code=404, detail="Workspace file not found.")
    return path


async def _save_upload(upload: UploadFile) -> dict:
    original = Path(upload.filename or "audio.wav").name
    if Path(original).suffix.lower() != ".wav":
        raise HTTPException(status_code=415, detail="For this MVP, upload WAV files only.")
    safe_stem = re.sub(r"[^A-Za-z0-9_-]+", "-", Path(original).stem).strip("-_")[:48] or "audio"
    name = f"{safe_stem}-{uuid.uuid4().hex[:10]}.wav"
    target = _safe_workspace_file(name, must_exist=False)
    total = 0
    try:
        with target.open("xb") as output:
            while True:
                chunk = await upload.read(CHUNK_SIZE)
                if not chunk:
                    break
                total += len(chunk)
                if total > MAX_UPLOAD_BYTES:
                    raise HTTPException(status_code=413, detail="Upload exceeds the 500 MiB limit.")
                output.write(chunk)
        if total == 0:
            target.unlink(missing_ok=True)
            raise HTTPException(status_code=400, detail="Uploaded file is empty.")
        # Decode now so corrupt/non-audio WAV files fail during import, not later.
        metadata = analyze_file(target)
        return {"file": name, "original_name": original, "bytes": total, "analysis": metadata}
    except HTTPException:
        target.unlink(missing_ok=True)
        raise
    except Exception as exc:
        target.unlink(missing_ok=True)
        raise HTTPException(status_code=422, detail=f"Could not read a valid WAV file: {type(exc).__name__}: {exc}") from exc
    finally:
        await upload.close()


@app.get("/")
def index() -> FileResponse:
    return FileResponse(UI_DIR / "index.html")


@app.get("/api/health")
def health() -> dict:
    return {
        "ok": True,
        "app": "VeryRare AI Studio",
        "version": app.version,
        "workspace": str(WORKSPACE),
        "cloud_audio_upload": False,
        "engine": "deterministic DSP MVP",
    }


@app.post("/api/import")
async def import_audio(
    vocal: Annotated[UploadFile, File()],
    beat: Annotated[UploadFile, File()],
) -> dict:
    vocal_result = await _save_upload(vocal)
    try:
        beat_result = await _save_upload(beat)
    except Exception:
        _safe_workspace_file(vocal_result["file"], must_exist=False).unlink(missing_ok=True)
        raise
    return {"vocal": vocal_result, "beat": beat_result}


@app.get("/api/analyze/{filename}")
def analyze(filename: str) -> dict:
    path = _safe_workspace_file(filename)
    try:
        return analyze_file(path)
    except Exception as exc:
        raise HTTPException(status_code=422, detail=f"Audio analysis failed: {type(exc).__name__}: {exc}") from exc


@app.post("/api/mix")
def render_mix(request: MixRequest) -> dict:
    vocal_path = _safe_workspace_file(request.vocal_file)
    beat_path = _safe_workspace_file(request.beat_file)
    output_name = f"VeryRare-Mix-{uuid.uuid4().hex[:10]}.wav"
    output_path = _safe_workspace_file(output_name, must_exist=False)
    settings = MixSettings(
        vocal_gain_db=request.vocal_gain_db,
        instrumental_gain_db=request.beat_gain_db,
        vocal_highpass_hz=request.highpass_hz,
        vocal_presence_db=request.presence_db,
        compression_ratio=request.compression_ratio,
        compression_threshold_db=request.compression_threshold_db,
        reverb_mix=request.reverb_mix,
        delay_mix=request.delay_mix,
        delay_ms=request.delay_ms,
        master_peak_dbfs=request.master_peak_dbfs,
    )
    try:
        report = mix_tracks(vocal_path, beat_path, output_path, settings)
        return {
            "rendered": True,
            "output_file": output_name,
            "audio_url": f"/api/audio/{output_name}",
            "report": report,
        }
    except Exception as exc:
        output_path.unlink(missing_ok=True)
        output_path.with_suffix(".report.json").unlink(missing_ok=True)
        raise HTTPException(status_code=422, detail=f"Render failed: {type(exc).__name__}: {exc}") from exc


@app.get("/api/audio/{filename}")
def audio_file(filename: str) -> FileResponse:
    path = _safe_workspace_file(filename)
    if path.suffix.lower() != ".wav":
        raise HTTPException(status_code=415, detail="Only WAV previews are served.")
    return FileResponse(path, media_type="audio/wav", filename=path.name)


@app.get("/api/capabilities")
def capabilities() -> dict:
    from app.plugin_catalog import CAPABILITIES
    return {
        "capabilities": [
            {
                "id": item.id,
                "name": item.name,
                "category": item.category,
                "status": item.status,
                "purpose": item.purpose,
                "safety_notes": item.safety_notes,
            }
            for item in CAPABILITIES
        ]
    }
